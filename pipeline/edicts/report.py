"""Write pipeline/report.md: what needs a human look after a build."""
from __future__ import annotations

from collections import Counter
from pathlib import Path

BULLET_TOLERANCE = 0.05


def _pct(n: int, total: int) -> str:
    return f"{n} ({100 * n / total:.1f}%)" if total else "0"


def _short(text: str, n: int = 140) -> str:
    text = text.replace("|", "/").replace("\n", " ")
    return text if len(text) <= n else text[: n - 1] + "…"


def write_report(path: Path, *, posts, patches, changes, chronicle, classes,
                 merge_notes, bullet_checks, problems) -> None:
    total = len(changes)
    by_cat = Counter(c["category"] for c in changes)
    by_kind = Counter(c["kind"] for c in changes)
    by_conf = Counter(c["confidence"] for c in changes)
    fallback = [c for c in changes if c["categorySource"] == "fallback"]
    many = [c for c in changes if len(c["classes"]) >= 3]
    per_class = Counter(cls for c in changes for cls in c["classes"])
    unused = [c["name"] for c in classes if per_class[c["name"]] == 0]
    no_faction = [c["name"] for c in classes if not c.get("faction")]

    versions = Counter(v for p in patches for v in p["versions"])
    dup_versions = sorted(v for v, n in versions.items() if n > 1)
    mismatches = []
    for pid, bullets, items in bullet_checks:
        if bullets and abs(bullets - items) / bullets > BULLET_TOLERANCE:
            mismatches.append((pid, bullets, items))

    kinds = Counter(p.kind for p in posts)
    skipped = [p for p in posts if p.kind == "skip"]
    unversioned = [p for p in patches if not p["version"]]

    L: list[str] = []
    w = L.append
    w("# Pipeline report\n")
    w("Generated by `pipeline/build_data.py`. Rebuilt on every run, so don't edit it by hand.\n")
    if problems:
        w("## Problems\n")
        L.extend(f"- {p}" for p in problems)
        w("")
    w("## Totals\n")
    w(f"- Posts read: {len(posts)} (patch {kinds['patch']}, chronicle {kinds['chronicle']}, "
      f"skipped {kinds['skip']})")
    w(f"- Patch records: {len(patches)}, unversioned: {len(unversioned)}")
    w(f"- Change items: {total}")
    w(f"- Chronicle posts after de-duplication: {len(chronicle)}")
    w("")
    w("| Category | Items |\n|---|---|")
    L.extend(f"| {k} | {_pct(v, total)} |" for k, v in by_cat.most_common())
    w("")
    w("| Kind | Items |\n|---|---|")
    L.extend(f"| {k} | {_pct(v, total)} |" for k, v in by_kind.most_common())
    w("")
    w("| Class evidence | Items |\n|---|---|")
    L.extend(f"| {k} | {_pct(v, total)} |" for k, v in by_conf.most_common())
    w("")
    w(f"Chronicle types: " + ", ".join(f"{k} {v}" for k, v in
                                       Counter(c["type"] for c in chronicle).most_common()))
    w("")

    w("## Checks\n")
    w(f"- Versions on more than one record: {', '.join(dup_versions) or 'none'}")
    w(f"- Patches whose item count differs from the bullet count by more than "
      f"{BULLET_TOLERANCE:.0%}: {len(mismatches)}")
    L.extend(f"  - {pid}: {b} bullets, {i} list items" for pid, b, i in mismatches)
    w(f"- Classes with no changes: {', '.join(unused) or 'none'}")
    w(f"- Classes without a faction: {len(no_faction)} of {len(classes)}")
    w("")

    w("## Merges\n")
    L.extend(f"- {n}" for n in merge_notes)
    multi = [p for p in patches if p["alsoPosted"]]
    w(f"- {len(multi)} patch records also link to other posts of the same release.")
    w("")

    w("## Unversioned patch records\n")
    L.extend(f"- {p['id']}: {p['title']}" for p in unversioned)
    w("")

    w(f"## Untagged items (fallback to Game-wide): {_pct(len(fallback), total)}\n")
    w("| Key | Patch | Section | Text |\n|---|---|---|---|")
    L.extend(f"| {c['key']} | {c['patch']} | {_short(' › '.join(c['section']), 50)} | "
             f"{_short(c['plain'])} |" for c in fallback)
    w("")

    w(f"## Items tagged with 3+ classes: {len(many)}\n")
    w("| Key | Patch | Classes | Text |\n|---|---|---|---|")
    L.extend(f"| {c['key']} | {c['patch']} | {', '.join(c['classes'])} | {_short(c['plain'])} |"
             for c in many)
    w("")

    w("## Changes per class\n")
    w("| Class | Items |\n|---|---|")
    L.extend(f"| {c['name']} | {per_class[c['name']]} |" for c in classes)
    w("")

    w("## Skipped posts\n")
    L.extend(f"- {p.date} [{p.source}] {p.title} ({p.type})" for p in
             sorted(skipped, key=lambda p: p.date))
    w("")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
